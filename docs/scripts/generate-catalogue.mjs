// Generates the catalogue the page renders, from the applications themselves.
//
// Every fact on the page is read out of an application's own `config.yaml`, so
// the site cannot describe something this repository does not ship. Adding an
// application directory is enough to put it on the page; there is nothing to
// remember and nothing generated to commit.
//
// Output is git-ignored and rebuilt by `npm run dev` and `npm run build`.

import {
  copyFile,
  mkdir,
  readFile,
  readdir,
  rm,
  writeFile,
} from 'node:fs/promises'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { parse } from 'yaml'

const here = dirname(fileURLToPath(import.meta.url))
const root = resolve(here, '..')
const repo = resolve(root, '..')

const generated = join(root, 'app', 'generated')
const icons = join(root, 'public', 'icons')

// Every top-level directory carrying a `config.yaml` is one application. That
// is how Home Assistant discovers them, so it is how the page discovers them.
async function applicationSlugs() {
  const entries = await readdir(repo, { withFileTypes: true })
  const slugs = []

  for (const entry of entries) {
    if (!entry.isDirectory() || entry.name.startsWith('.')) continue

    try {
      await readFile(join(repo, entry.name, 'config.yaml'))
      slugs.push(entry.name)
    } catch {
      // Not an application. `docs/` lands here.
    }
  }

  return slugs.sort()
}

// How the application is reached, in the order Home Assistant resolves it:
// ingress replaces a published port, and some applications serve no web
// interface at all.
function access(config) {
  if (config.ingress === true) return { kind: 'ingress', label: 'Ingress' }

  if (typeof config.webui === 'string') {
    const port = config.webui.match(/\[PORT:(\d+)\]/)?.[1]
    if (port) return { kind: 'port', label: `Port ${port}` }
  }

  return { kind: 'none', label: 'No web interface' }
}

// The store shows the whole description; a card has room for the opening
// sentence, which is written as the tagline in every application here.
function tagline(description) {
  const text = String(description).replace(/\s+/g, ' ').trim()
  const end = text.indexOf('. ')

  return end === -1 ? text : text.slice(0, end + 1)
}

await rm(generated, { force: true, recursive: true })
await rm(icons, { force: true, recursive: true })
await mkdir(generated, { recursive: true })
await mkdir(icons, { recursive: true })

const applications = []

for (const slug of await applicationSlugs()) {
  const config = parse(await readFile(join(repo, slug, 'config.yaml'), 'utf8'))

  await copyFile(join(repo, slug, 'icon.png'), join(icons, `${slug}.png`))

  applications.push({
    access: access(config),
    icon: `icons/${slug}.png`,
    name: config.name,
    slug,
    tagline: tagline(config.description),
    url: config.url,
    version: config.version,
  })
}

const module = `// AUTO-GENERATED by scripts/generate-catalogue.mjs from each application's
// config.yaml. Do not hand-edit, and do not commit — it is rebuilt by
// \`npm run dev\` and \`npm run build\`.

export type Access = {
  kind: 'ingress' | 'none' | 'port'
  label: string
}

export type Application = {
  access: Access
  icon: string
  name: string
  slug: string
  tagline: string
  url: string
  version: string
}

export const applications: Application[] = ${JSON.stringify(applications, null, 2)}
`

await writeFile(join(generated, 'applications.ts'), module)

console.log(
  `Generated ${applications.length} application(s) into app/generated/.`,
)
